#!/bin/bash
# =====================================================================
# Bootstrap-скрипт для автоматической установки EasyTier
# Скачивает install.sh с GitHub, делает исполняемым и запускает.
# =====================================================================

set -e  # Прерывать выполнение при любой ошибке

# -------------------------- НАСТРОЙКИ ---------------------------------
# Замените URL на актуальный путь к вашему install.sh в репозитории
DEFAULT_REPO_URL="https://raw.githubusercontent.com/ваш-пользователь/ваш-репозиторий/main/install.sh"
# ---------------------------------------------------------------------

# Используем переданный аргумент или значение по умолчанию
REPO_URL="${1:-$DEFAULT_REPO_URL}"

# ------------------------------------------
# 1. Проверка прав (запуск от root)
# ------------------------------------------
if [ "$EUID" -ne 0 ]; then
    echo -e "\n🔐 Требуются права root. Перезапускаем с sudo...\n"
    exec sudo "$0" "$@"
    exit $?
fi

# ------------------------------------------
# 2. Установка curl и unzip
# ------------------------------------------
echo -e "\n📦 Обновление списка пакетов и установка curl, unzip...\n"
apt update -qq
apt install -y curl unzip

# ------------------------------------------
# 3. Скачивание основного скрипта install.sh
# ------------------------------------------
echo -e "\n⬇️  Скачивание install.sh из $REPO_URL ...\n"
curl -L -o install.sh "$REPO_URL"

# Проверка, что файл скачался
if [ ! -f install.sh ]; then
    echo "❌ Ошибка: не удалось скачать install.sh"
    exit 1
fi

# ------------------------------------------
# 4. Делаем скрипт исполняемым
# ------------------------------------------
chmod +x install.sh
echo -e "\n✅ Скрипт install.sh готов к запуску."

# ------------------------------------------
# 5. Запуск установки
# ------------------------------------------
echo -e "\n🚀 Запуск установки EasyTier...\n"
./install.sh install

# ------------------------------------------
# 6. Завершение
# ------------------------------------------
echo -e "\n🎉 Установка завершена. Управляйте службой через systemctl или rc-service."